"""Upload the curated Clone Pictures images to Cloudinary and write js/photos.js.

Usage:  python scripts/upload_to_cloudinary.py
Reads CLOUDINARY_URL (cloudinary://key:secret@cloud) from the environment or .env.
Images are fetched by Cloudinary straight from their source URLs (Pixieset / Instagram);
if that fails, the bytes are downloaded locally and uploaded instead.
"""
import hashlib
import json
import os
import time
import urllib.parse
import urllib.request
import uuid
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = "clone-studio"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"


def load_credentials():
    url = os.environ.get("CLOUDINARY_URL")
    env = ROOT / ".env"
    if not url and env.exists():
        for line in env.read_text().splitlines():
            if line.startswith("CLOUDINARY_URL="):
                url = line.split("=", 1)[1].strip()
    if not url:
        raise SystemExit("CLOUDINARY_URL is not set")
    parsed = urllib.parse.urlparse(url)
    return parsed.username, parsed.password, parsed.hostname


API_KEY, API_SECRET, CLOUD = load_credentials()
ENDPOINT = f"https://api.cloudinary.com/v1_1/{CLOUD}/image/upload"


def sign(params):
    payload = "&".join(f"{k}={params[k]}" for k in sorted(params))
    return hashlib.sha1((payload + API_SECRET).encode()).hexdigest()


def multipart(fields, file_bytes=None):
    boundary = uuid.uuid4().hex
    parts = []
    for k, v in fields.items():
        parts.append(f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'.encode())
    if file_bytes is not None:
        parts.append(
            f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="image.jpg"\r\n'
            f"Content-Type: image/jpeg\r\n\r\n".encode() + file_bytes + b"\r\n"
        )
    parts.append(f"--{boundary}--\r\n".encode())
    return b"".join(parts), f"multipart/form-data; boundary={boundary}"


def upload(item):
    params = {
        "public_id": f"{FOLDER}/{item['category']}/{item['id']}",
        "overwrite": "true",
        "timestamp": str(int(time.time())),
    }
    signed = {**params, "api_key": API_KEY, "signature": sign(params)}
    try:
        body, ctype = multipart({**signed, "file": item["source"]})
        res = urllib.request.urlopen(urllib.request.Request(ENDPOINT, body, {"Content-Type": ctype}), timeout=120)
    except urllib.error.HTTPError:
        src = urllib.request.urlopen(
            urllib.request.Request(item["source"], headers={"User-Agent": UA, "Referer": "https://clonepictures.pixieset.com/"}),
            timeout=120,
        ).read()
        body, ctype = multipart(signed, src)
        res = urllib.request.urlopen(urllib.request.Request(ENDPOINT, body, {"Content-Type": ctype}), timeout=180)
    data = json.loads(res.read())
    print("uploaded", data["public_id"])
    out = {k: item[k] for k in ("id", "category", "origin") if k in item}
    out.update(public_id=data["public_id"], version=data["version"], w=data["width"], h=data["height"])
    for k in ("post", "caption"):
        if k in item:
            out[k] = item[k]
    return out


def main():
    sources = json.loads((ROOT / "scripts" / "sources.json").read_text())
    with ThreadPoolExecutor(6) as pool:
        photos = list(pool.map(upload, sources))
    js = (
        "// Generated by scripts/upload_to_cloudinary.py — do not edit by hand.\n"
        f"window.CLONE_CLOUD = {json.dumps(CLOUD)};\n"
        f"window.CLONE_PHOTOS = {json.dumps(photos, indent=1, ensure_ascii=False)};\n"
    )
    (ROOT / "js" / "photos.js").write_text(js, encoding="utf-8")
    print(f"wrote js/photos.js with {len(photos)} photos")


if __name__ == "__main__":
    main()
